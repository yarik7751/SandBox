package com.joy.sandbox.core.dungeon.model

/**
 * Игровые механики, задействованные на уровне.
 * [id] — тех. ключ для сохранения факта прочтения интро механики.
 */
enum class DungeonMechanic(val id: String) {

    /** Базовые правила игры — показываются на первом уровне. */
    BASE("base"),

    /** Заклинившие двери: отсутствуют на доске, переключение отклоняется. */
    JAMMED("jammed"),

    /** Укрытия: тёмные клетки, в которых враг не видит персонажей и не входит. */
    CONCEALED("concealed"),

    /** Завалы: клетки, куда не может войти никто. */
    BLOCKED("blocked"),

    /** Лимит переключений дверей героем. */
    TOGGLES_BUDGET("toggles_budget"),

    /** Враг в ловушке может выломать закрытую дверь на пути к цели. */
    ENEMY_DOOR_CHARGE("enemy_door_charge"),

    /** Запас ходов без ответа врага. */
    EXTRA_MOVES("extra_moves"),
}
